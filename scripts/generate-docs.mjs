import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { catalogue, DESCRIPTION, SETUP_GUIDANCE } from "../dist/src/catalogue.js";

const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const generated = "<!-- Generated by scripts/generate-docs.mjs from src/catalogue.ts. Do not hand-edit. -->";
const escape = (value) => value.replaceAll("|", "\\|").replaceAll("\n", " ");
const commands = Object.entries(catalogue).sort(([a], [b]) => a.localeCompare(b, "en"));
for (const [name, entry] of commands) {
  if (!["read", "write", "read/write"].includes(entry.effect)) throw new Error(`Missing command effect: ${name}`);
}
const invocation = (example) => example.replace(/^hybrid-axi(?= |$)/, "npx -y @knowttl/hybrid-axi");
const table = (prefix) => ["| Command | Effect | Purpose |", "|---|---|---|", ...commands.map(([name, entry]) =>
  `| \`${prefix} ${name}\` | ${entry.effect} | ${escape(entry.description)} |`)].join("\n");
const policy = `Read/write classifies API effects, including guarded downloads and consuming GETs.
\`report file\` is read for normal report types and write for bin, dropped-files and memory.
Quick scans are read exceptions that transmit the supplied sample or URL.
\`setup hooks\` writes local agent configuration only and requires an explicit request.
API writes require a file profile's allowWrites and exact operation allowlist, preview, --execute and the exact preview --confirm string.
HYBRID_AXI_READ_ONLY=true overrides all API write policies.
Never replay an ambiguous outcome; reconcile the audit ID, private journal and known result IDs.
Downloads require an explicit new output path; save upstream bytes unchanged, never extract or execute.
Gzip/ZIP delivery does not guarantee password protection.\n`;
const reference = `${generated}

# Command reference

${DESCRIPTION}.
Run each command with \`--help\` for required selectors, defaults and examples.

${policy}
${table("hybrid-axi")}

${commands.map(([name, entry]) => [
  `## ${name}`, "", `Effect: **${entry.effect}**.`, "", entry.description, "",
  "| Flag | Meaning |", "|---|---|", ...Object.entries(entry.flags).map(([flag, meaning]) => `| \`${flag}\` | ${escape(meaning)} |`), "",
  "```sh", ...entry.examples, "```", "",
].join("\n")).join("\n")}`;
const skill = `---
name: hybrid-axi
description: "Investigate Hybrid Analysis hashes, reports, feeds, searches and experimental YARA hunting; preview and execute explicitly scoped submissions, hunting changes and guarded downloads through compact TOON output."
user-invocable: false
---

${generated}

# hybrid-axi

${DESCRIPTION}.
Use \`npx -y @knowttl/hybrid-axi\` without a global install.
Bare \`--version\`, \`-v\` and \`-V\` print the package version.

${SETUP_GUIDANCE.replaceAll("hybrid-axi", "npx -y @knowttl/hybrid-axi")}.
Credentials use environment/file SecretRefs, never inline secrets or chat.
The default key reference is HYBRID_AXI_API_KEY.
Only \`https://hybrid-analysis.com/api/v2\` and \`https://hybrid-analysis.com/api/labs\` are supported.

Start with local discovery:

\`\`\`sh
${catalogue.home.examples.map(invocation).join("\n")}
${invocation(catalogue["auth status"].examples[0])}
\`\`\`

Home and the optional session hook read local profile context only, without HTTP or reading credential files.
Install integrations only on explicit request through \`npx -y @knowttl/hybrid-axi setup hooks\`.

${policy}
Sandbox submission previews disclose that the sample and report can become visible to the community.
Hunting matches marks returned matches delivered and cannot be replayed safely.
Labs contracts are experimental; unknown fields remain available with --fields or --full after redaction.
Credential issuance, abuse-report creation, overview refresh and arbitrary HTTP are unavailable.
Never interpret denial or malformed data as an empty result, or automatically submit a missing hash.
Preserve profile, filters and known query IDs when resuming bounded results.
Use a command's --help for required selectors, defaults and examples.
See the [command reference](https://github.com/knowttl/hybrid-axi/blob/main/docs/commands.md) for all flags.

## Orientation

${table("npx -y @knowttl/hybrid-axi")}
`;
const readmePath = new URL("README.md", root);
const readme = readFileSync(readmePath, "utf8");
const start = "<!-- command-registry:start -->\n", end = "\n<!-- command-registry:end -->";
if (readme.split(start).length !== 2 || readme.split(end).length !== 2) throw new Error("README command registry markers missing or duplicated");
const summary = `${readme.split(start)[0]}${start}${table("hybrid-axi")}${end}${readme.split(end)[1]}`;
const outputs = new Map([["docs/commands.md", `${reference.trimEnd()}\n`], ["skills/hybrid-axi/SKILL.md", skill], ["README.md", summary]]);
let stale = false;
for (const [path, content] of outputs) {
  const url = new URL(path, root);
  if (check) {
    let current;
    try { current = readFileSync(url, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (current !== content) { process.stderr.write(`Stale generated documentation: ${path}; build then run pnpm run docs:generate\n`); stale = true; }
  } else {
    mkdirSync(dirname(fileURLToPath(url)), { recursive: true });
    writeFileSync(url, content);
  }
}
if (stale) process.exitCode = 1;
